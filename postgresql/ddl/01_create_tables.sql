-- Phase 4 | Step 3 | Run in POSTGRESQL as miglab
-- Tables with PK / UK / CHECK only. FKs and indexes are added after the load.
-- 7 Oracle sequences + 7 BEFORE INSERT triggers are replaced by identity columns.
 
CREATE TABLE miglab.provider (
    provider_id        bigint GENERATED BY DEFAULT AS IDENTITY,
    provider_code      varchar(20)  NOT NULL,
    provider_name      varchar(150) NOT NULL,
    specialty          varchar(100),
    state_code         varchar(2),
    active_flag        char(1)      DEFAULT 'Y',
    created_date       timestamp(0) DEFAULT localtimestamp(0),
    updated_timestamp  timestamp(6) DEFAULT localtimestamp,
    CONSTRAINT pk_provider        PRIMARY KEY (provider_id),
    CONSTRAINT uk_provider_code   UNIQUE (provider_code),
    CONSTRAINT ck_provider_active CHECK (active_flag IN ('Y','N'))
);
 
CREATE TABLE miglab.member (
    member_id          bigint GENERATED BY DEFAULT AS IDENTITY,
    member_number      varchar(30)  NOT NULL,
    first_name         varchar(100),
    last_name          varchar(100),
    date_of_birth      date,
    state_code         varchar(2),
    active_flag        char(1)      DEFAULT 'Y',
    created_date       timestamp(0) DEFAULT localtimestamp(0),
    CONSTRAINT pk_member        PRIMARY KEY (member_id),
    CONSTRAINT uk_member_number UNIQUE (member_number),
    CONSTRAINT ck_member_active CHECK (active_flag IN ('Y','N'))
);
 
CREATE TABLE miglab.fee_schedule (
    schedule_id        bigint GENERATED BY DEFAULT AS IDENTITY,
    schedule_code      varchar(30)  NOT NULL,
    schedule_name      varchar(150),
    effective_date     date         NOT NULL,
    termination_date   date,
    status             varchar(20)  DEFAULT 'ACTIVE',
    description        text,
    created_date       timestamp(0) DEFAULT localtimestamp(0),
    updated_timestamp  timestamp(6) DEFAULT localtimestamp,
    CONSTRAINT pk_fee_schedule        PRIMARY KEY (schedule_id),
    CONSTRAINT uk_fee_schedule_code   UNIQUE (schedule_code),
    CONSTRAINT ck_fee_schedule_status CHECK (status IN ('ACTIVE','INACTIVE'))
);
 
CREATE TABLE miglab.fee_schedule_detail (
    schedule_detail_id bigint GENERATED BY DEFAULT AS IDENTITY,
    schedule_id        bigint        NOT NULL,
    procedure_code     varchar(20)   NOT NULL,
    modifier_code      varchar(10),
    allowed_amount     numeric(12,2) NOT NULL,
    effective_date     date          NOT NULL,
    termination_date   date,
    CONSTRAINT pk_fee_schedule_detail PRIMARY KEY (schedule_detail_id)
);
 
CREATE TABLE miglab.claim (
    claim_id           bigint GENERATED BY DEFAULT AS IDENTITY,
    claim_number       varchar(30)   NOT NULL,
    member_id          bigint        NOT NULL,
    provider_id        bigint        NOT NULL,
    service_date       date          NOT NULL,
    received_date      timestamp(0)  DEFAULT localtimestamp(0),
    claim_status       varchar(20),
    total_billed       numeric(14,2),
    total_allowed      numeric(14,2),
    created_timestamp  timestamp(6)  DEFAULT localtimestamp,
    CONSTRAINT pk_claim        PRIMARY KEY (claim_id),
    CONSTRAINT uk_claim_number UNIQUE (claim_number),
    CONSTRAINT ck_claim_status CHECK (claim_status IN ('NEW','PROCESSING','PAID','DENIED'))
);
 
CREATE TABLE miglab.claim_detail (
    claim_detail_id    bigint GENERATED BY DEFAULT AS IDENTITY,
    claim_id           bigint        NOT NULL,
    line_number        integer       NOT NULL,
    procedure_code     varchar(20),
    modifier_code      varchar(10),
    billed_amount      numeric(12,2),
    allowed_amount     numeric(12,2),
    CONSTRAINT pk_claim_detail PRIMARY KEY (claim_detail_id),
    CONSTRAINT uk_claim_line   UNIQUE (claim_id, line_number)
);
 
CREATE TABLE miglab.migration_audit (
    audit_id           bigint GENERATED BY DEFAULT AS IDENTITY,
    process_name       varchar(100),
    source_count       bigint,
    target_count       bigint,
    status             varchar(20),
    message            varchar(4000),
    created_timestamp  timestamp(6) DEFAULT localtimestamp,
    CONSTRAINT pk_migration_audit PRIMARY KEY (audit_id)
);
 
-- Validation: expect 7 rows
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'miglab'
ORDER BY table_name;
